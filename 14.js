/*
Para utilizar um breakpoint sem escrever "debugger" no código:

1. Abrir as ferramentas de desenvolvedor com F12.
2. Ir para a aba "Sources".
3. Abrir o arquivo JavaScript.
4. Clicar no número da linha onde deseja colocar um breakpoint.
5. Recarregar a página ou executar o código.
6. Quando a execução chegar ao breakpoint, o navegador irá pausar.
7. Para continuar a execução normalmente, clicar no botão
   "Resume script execution" (▶) ou pressionar F8.

Para remover um breakpoint:
- Clicar novamente no número da linha onde ele foi colocado.

Para remover todos de uma vez:
- No painel de breakpoints, usar a opção para desmarcar/remover
  todos os breakpoints.
*/
